import { chromium } from "@playwright/test";
import { join } from "node:path";
const [base, root] = process.argv.slice(2);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, reducedMotion: "reduce" });
await ctx.addCookies([{ name: "fake-scenario", value: "happy", url: base }]);
const page = await ctx.newPage();
await page.goto(base);
await page.locator('input[type="file"]').first().setInputFiles(join(root, "e2e/fixtures/tiny.webm"));
await page.getByRole("img", { name: /screenshot for step 4/i }).waitFor();
await page.getByRole("button", { name: /^export options/i }).click();
await page.getByRole("dialog").waitFor();
await page.getByRole("button", { name: /add blank column/i }).click();
await page.getByRole("textbox", { name: /header for blank column/i }).fill("Pass/Fail");
await page.getByRole("checkbox", { name: /description/i }).uncheck();
await page.getByRole("textbox", { name: /header for expected result/i }).fill("Expected outcome");
await page.waitForTimeout(500);
console.log("blank header =", await page.getByRole("textbox", { name: /header for blank column/i }).inputValue());
await page.screenshot({ path: join(root, "docs/screenshots/08-export-options.png") });
await browser.close();
